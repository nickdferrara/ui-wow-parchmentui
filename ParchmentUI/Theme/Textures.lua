local ADDON_NAME, ns = ...

local Textures = {}
ns.Textures = Textures

local ART_PATH = "Interface\\AddOns\\" .. ADDON_NAME .. "\\Art\\"
local entries = {}

-- Window modules refer to artwork by key only, so a file can be renamed in one place.
-- info holds the pixel size of the file and, for nine-slice art, the width of the border that
-- must not be stretched.
function Textures.Register(key, fileName, info)
    assert(entries[key] == nil, "texture registered twice: " .. tostring(key))
    entries[key] = {
        path = ART_PATH .. fileName,
        width = info.width,
        height = info.height,
        margin = info.margin,
    }
end

function Textures.Get(key)
    local entry = entries[key]
    return entry and entry.path
end

-- Returns the registered width, height and nine-slice margin of a texture.
function Textures.Info(key)
    local entry = entries[key]
    if not entry then
        return nil
    end
    return entry.width, entry.height, entry.margin
end

function Textures.Keys()
    local keys = {}
    for key in pairs(entries) do
        keys[#keys + 1] = key
    end
    table.sort(keys)
    return keys
end

-- All artwork is near-white with an alpha channel and is tinted with theme colors when used,
-- so one file serves both themes. The files are generated by art/generate_textures.py.
Textures.Register("scrollSurface", "ScrollSurface.tga", { width = 256, height = 256, margin = 48 })
Textures.Register("scrollRoll", "ScrollRoll.tga", { width = 256, height = 32, margin = 16 })
Textures.Register("divider", "Divider.tga", { width = 256, height = 8 })
Textures.Register("buttonOutline", "ButtonOutline.tga", { width = 64, height = 64, margin = 16 })
